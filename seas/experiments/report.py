"""Generate results/RESULTS.md and poster/generated/results.tex from analysed results.

Every number on the poster comes from these generated macros (no hand-typed results)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

from seas.experiments.stats import add_common_idle

POLS = ["fifo-ff", "eft", "eft-slack", "energy-greedy", "seas", "seas-eps"]


def _pct(x: float, nd: int = 1) -> str:
    return f"{x * 100:.{nd}f}"


def _p(p: float) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def policy_table(df: pd.DataFrame, point: str) -> str:
    g = df[df.point == point]
    lines = [
        "| policy | dyn. energy kJ (mean) | miss % | late % | expired % | rejected (inelig.) | GPU share | mean resp. s |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for p in [x for x in POLS if x in set(g.policy_spec)] + sorted(set(g.policy_spec) - set(POLS)):
        h = g[g.policy_spec == p]
        lines.append(
            f"| {p} | {h.energy_dyn_J.mean() / 1e3:.1f} | {_pct(h.miss_rate.mean())} | {_pct(h.late_rate.mean())} | "
            f"{_pct(h.expire_rate.mean())} | {h.rejected_ineligible.mean():.1f} | {h.gpu_share.mean():.2f} | "
            f"{h.mean_response_s.mean():.1f} |"
        )
    return "\n".join(lines)


def write_report(root: Path, conf: dict[str, Any], poster_dir: Path) -> None:
    s = conf["summary"]
    h1, h2, h3, h4 = conf["H1"], conf["H2"], conf["H3"], conf["H4"]
    h3k = h3["noise_sigma=0.25"]
    md = [
        "# Stage-1 results (generated by `seas report`; do not edit by hand)",
        "",
        "All energies are **modelled** from synthetic profiles in simulation. Security is **simulated "
        "capability eligibility**; no TEE executed. 30 paired seeds per configuration.",
        "",
        "## Confirmatory hypotheses (preregistered, Holm over H1–H3)",
        "",
        "| hypothesis | p (raw) | p (Holm) | verdict |",
        "|---|---|---|---|",
    ]
    for k in ("H1", "H2", "H3"):
        md.append(
            f"| {k} | {_p(s[k]['p'])} | {_p(s[k]['p_holm'])} | {'supported' if s[k]['supported'] else 'NOT supported'} |"
        )
    md += [
        "",
        "### H1 (S1): energy superiority + miss-rate non-inferiority vs EFT",
        "",
        f"* Relative dynamic energy seas/EFT − 1: mean {_pct(h1['energy_rel_mean'], 2)} % "
        f"(95 % CI {_pct(h1['energy_rel_ci'][0], 2)} … {_pct(h1['energy_rel_ci'][1], 2)} %), "
        f"Wilcoxon one-sided p = {_p(h1['p_energy'])}, r_rb = {h1['r_rb_energy']:.2f}.",
        f"* Miss rate: seas {_pct(h1['miss_seas_mean'])} % vs EFT {_pct(h1['miss_eft_mean'])} %; mean paired difference "
        f"{_pct(h1['ni_mean_diff'], 2)} pp, one-sided 95 % upper bound {_pct(h1['ni_upper95_t'], 2)} pp "
        f"(bootstrap {_pct(h1['ni_upper95_boot'], 2)} pp) vs margin {_pct(h1['ni_margin'], 0)} pp; "
        f"p_NI = {_p(h1['ni_p_ni_t'])} (Wilcoxon sensitivity p = {_p(h1['ni_p_ni_wilcoxon'])}).",
        f"* Ablation: seas vs EFT-slack {_pct(h1['ablation_seas_vs_eftslack_rel_mean'], 2)} % "
        f"(CI {_pct(h1['ablation_seas_vs_eftslack_rel_ci'][0], 2)} … {_pct(h1['ablation_seas_vs_eftslack_rel_ci'][1], 2)} %, "
        f"p = {_p(h1['ablation_seas_vs_eftslack_p_less'])}); EFT-slack vs EFT "
        f"{_pct(h1['ablation_eftslack_vs_eft_rel_mean'], 2)} % "
        f"(CI {_pct(h1['ablation_eftslack_vs_eft_rel_ci'][0], 2)} … {_pct(h1['ablation_eftslack_vs_eft_rel_ci'][1], 2)} %).",
        "",
        "### H2 (S4): gain vs secure-job fraction",
        "",
        "| secure fraction | mean energy gain vs EFT % | 95 % CI |",
        "|---|---|---|",
    ]
    for lv, g, ci in zip(h2["levels"], h2["mean_gain_by_level"], h2["gain_ci_by_level"], strict=True):
        md.append(f"| {lv:.1f} | {_pct(g, 2)} | {_pct(ci[0], 2)} … {_pct(ci[1], 2)} |")
    md += [
        f"\nPer-seed OLS slope: mean {h2['slope_mean'] * 100:.2f} pp per unit fraction "
        f"(CI {h2['slope_ci'][0] * 100:.2f} … {h2['slope_ci'][1] * 100:.2f}), Wilcoxon (greater) p = {_p(h2['p_slope_greater'])}.",
        "",
        "### H3 (S7): robustness to estimation error",
        "",
        "| σ | energy seas vs EFT % (CI) | p | miss seas − greedy pp (CI) | p | miss seas − EFT pp |",
        "|---|---|---|---|---|---|",
    ]
    for pt, v in sorted(h3.items()):
        md.append(
            f"| {pt.split('=')[1]} | {_pct(v['energy_rel_mean'], 2)} ({_pct(v['energy_rel_ci'][0], 2)} … {_pct(v['energy_rel_ci'][1], 2)}) "
            f"| {_p(v['p_energy_less'])} | {_pct(v['miss_diff_vs_greedy_mean'], 2)} ({_pct(v['miss_diff_ci'][0], 2)} … "
            f"{_pct(v['miss_diff_ci'][1], 2)}) | {_p(v['p_miss_less_vs_greedy'])} | {_pct(v['miss_diff_vs_eft_mean'], 2)} |"
        )
    md += [
        "",
        "### H4 (S1, descriptive): are deadlines binding?",
        "",
        f"Energy-greedy minus seas miss rate: {_pct(h4['mean_diff_greedy_minus_seas'], 2)} pp "
        f"(CI {_pct(h4['ci'][0], 2)} … {_pct(h4['ci'][1], 2)}); criterion ≥ 5 pp → "
        f"{'binding' if h4['binding'] else 'NOT binding'}. Energy-greedy energy vs seas: {_pct(h4['greedy_energy_rel_vs_seas'], 2)} %.",
        "",
    ]
    for sc in ("S1", "S2", "S3", "S4", "S5", "S6", "S7", "E-load"):
        f = root / sc / "runs.csv"
        if not f.exists():
            continue
        df = add_common_idle(pd.read_csv(f))
        md += [f"## {sc} ({df.status.iloc[0]})", ""]
        for pt in sorted(df.point.unique()):
            md += [f"**{pt}**", "", policy_table(df, pt), ""]
        if sc == "S1":
            g = df[df.point == "base"]
            md += [
                "Energy accounting (S1, mean over seeds, kJ): dynamic / idle always-on over common horizon / "
                "idle with ideal power-gating (exploratory S8):",
                "",
                "| policy | dynamic | idle (always-on, common horizon) | idle (power-gated, ideal) | dyn. relaxation LB |",
                "|---|---|---|---|---|",
            ]
            for p in POLS:
                h = g[g.policy_spec == p]
                md.append(
                    f"| {p} | {h.energy_dyn_J.mean() / 1e3:.1f} | {h.energy_idle_common_J.mean() / 1e3:.1f} | "
                    f"{h.energy_idle_busy_J.mean() / 1e3:.1f} | {h.energy_lb_J.mean() / 1e3:.1f} |"
                )
            md += [
                "",
                f"No-choice fraction (jobs with exactly one eligible node): {g.no_choice_fraction.mean():.3f}.",
                "",
            ]
    f = root / "scaling" / "runs.csv"
    if f.exists():
        sdf = pd.read_csv(f)
        md += [
            "## Scaling (exploratory, wall-clock, machine-dependent)",
            "",
            "| nodes | jobs | policy | mean decision µs | p95 decision µs |",
            "|---|---|---|---|---|",
        ]
        for (n, pol), g in sdf.groupby(["nodes", "policy"]):
            md.append(
                f"| {n} | {g.jobs.iloc[0]} | {pol} | {g.sched_mean_us.mean():.0f} | {g.sched_p95_us.mean():.0f} |"
            )
    (root / "RESULTS.md").write_text("\n".join(md) + "\n")

    # LaTeX macros for the poster
    s1 = add_common_idle(pd.read_csv(root / "S1" / "runs.csv"))
    gb = s1[s1.point == "base"]

    def mean(p: str, m: str) -> float:
        return float(gb[gb.policy_spec == p][m].mean())

    mac = {
        "HOneEnergyRel": _pct(h1["energy_rel_mean"], 1),
        "HOneEnergyLo": _pct(h1["energy_rel_ci"][0], 1),
        "HOneEnergyHi": _pct(h1["energy_rel_ci"][1], 1),
        "HOnePEnergy": _p(h1["p_energy"]),
        "HOneMissSeas": _pct(h1["miss_seas_mean"], 1),
        "HOneMissEft": _pct(h1["miss_eft_mean"], 1),
        "HOneNIUpper": _pct(h1["ni_upper95_t"], 1),
        "HOneNIMargin": _pct(h1["ni_margin"], 0),
        "HOnePNI": _p(h1["ni_p_ni_t"]),
        "HOneVerdict": "supported" if s["H1"]["supported"] else "not supported",
        "HOnePHolm": _p(s["H1"]["p_holm"]),
        "AblSeasVsSlack": _pct(h1["ablation_seas_vs_eftslack_rel_mean"], 1),
        "AblSlackVsEft": _pct(h1["ablation_eftslack_vs_eft_rel_mean"], 1),
        "HTwoSlope": f"{h2['slope_mean'] * 100:.1f}",
        "HTwoSlopeLo": f"{h2['slope_ci'][0] * 100:.1f}",
        "HTwoSlopeHi": f"{h2['slope_ci'][1] * 100:.1f}",
        "HTwoPHolm": _p(s["H2"]["p_holm"]),
        "HTwoVerdict": "supported" if s["H2"]["supported"] else "not supported",
        "HTwoGainZero": _pct(h2["mean_gain_by_level"][0], 1),
        "HTwoGainMax": _pct(h2["mean_gain_by_level"][-1], 1),
        "HThreeEnergyRel": _pct(h3k["energy_rel_mean"], 1),
        "HThreeMissVsGreedy": _pct(h3k["miss_diff_vs_greedy_mean"], 1),
        "HThreePHolm": _p(s["H3"]["p_holm"]),
        "HThreeVerdict": "supported" if s["H3"]["supported"] else "not supported",
        "HFourDiff": _pct(h4["mean_diff_greedy_minus_seas"], 1),
        "HFourVerdict": "binding" if h4["binding"] else "not binding",
        "GreedyEnergyRel": _pct(h4["greedy_energy_rel_vs_seas"], 1),
        "FifoEnergyKJ": f"{mean('fifo-ff', 'energy_dyn_J') / 1e3:.0f}",
        "EftEnergyKJ": f"{mean('eft', 'energy_dyn_J') / 1e3:.0f}",
        "SeasEnergyKJ": f"{mean('seas', 'energy_dyn_J') / 1e3:.0f}",
        "IdleCommonKJ": f"{mean('seas', 'energy_idle_common_J') / 1e3:.0f}",
        "IdleShare": _pct(mean("seas", "energy_idle_common_J") / mean("seas", "energy_total_common_J"), 0),
        "NoChoice": _pct(float(gb.no_choice_fraction.mean()), 0),
        "Violations": str(int(s1["eligibility_violations"].sum())),
    }
    for sc in ("S4", "S7", "S2", "S3", "S5", "E-load"):
        f = root / sc / "runs.csv"
        if f.exists():
            mac["Violations"] = str(int(mac["Violations"]) + int(pd.read_csv(f)["eligibility_violations"].sum()))
    n_runs = sum(len(pd.read_csv(f)) for f in root.glob("*/runs.csv") if f.parent.name != "scaling")
    mac["NRuns"] = f"{n_runs:,}".replace(",", "\\,")
    gen = poster_dir / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    tex = ["% generated by `seas report` from results/ — do not edit"]
    tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
    (gen / "results.tex").write_text("\n".join(tex) + "\n")
    (root / "CONFIRMATORY.json").write_text(json.dumps(conf, indent=1, default=float))
